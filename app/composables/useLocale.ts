const translations: Record<Locale, typeof en> = { en, de }

let _isLocaleInitialized = false

export function useLocale() {
  const locale = useState<Locale>('locale', () => 'en')

  // Restore from localStorage on client AFTER hydration to prevent class attribute mismatches
  if (import.meta.client && !_isLocaleInitialized) {
    _isLocaleInitialized = true
    onNuxtReady(() => {
      const stored = localStorage.getItem('locale') as Locale | null
      if (stored && stored !== locale.value && (stored === 'en' || stored === 'de')) {
        locale.value = stored
      }
    })
  }

  function setLocale(l: Locale) {
    locale.value = l
    if (import.meta.client) localStorage.setItem('locale', l)
  }

  function t(path: string, vars?: Record<string, string | number>): string {
    const keys = path.split('.')
    let val: unknown = translations[locale.value]
    for (const k of keys) {
      if (val && typeof val === 'object') val = (val as Record<string, unknown>)[k]
      else return path
    }
    if (typeof val !== 'string') return path
    if (!vars) return val
    return val.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`))
  }

  return { locale, setLocale, t }
}
